function tx(
  hash: string,
  chain: Chain,
  from: string,
  to: string,
  value: number,
  token: string | null,
  timestamp: string,
  block: number,
  raw: TxTypeRaw,
  gas: number | null = 21000,
  contract: string | null = null,
): NormalizedTransaction {
  return {
    tx_hash: hash,
    chain,
    from_address: from,
    to_address: to,
    value,
    token,
    token_contract: contract,
    timestamp,
    block_number: block,
    tx_type_raw: raw,
    gas_used: gas,
  };
}

function edge(
  id: string,
  from: string,
  to: string,
  classification: HopClass,
  transaction: NormalizedTransaction,
  confidenceDelta: number,
  evidence: string,
  correlation: GraphEdge["correlation"] = "none",
): GraphEdge {
  return { id, from, to, classification, tx: transaction, confidenceDelta, evidence, correlation };
}

